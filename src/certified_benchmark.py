#!/usr/bin/env python3
"""Horizon-8 tube MPC with calibrated risk accounting.

Run `python certified_benchmark.py --output results --episodes 500`.
The manuscript and README specify the model and statistical construction.
Only NumPy, SciPy and pandas are required. All output data are generated by solves.
"""
from __future__ import annotations
import argparse, json, time, platform
from pathlib import Path
from dataclasses import dataclass
import numpy as np
import pandas as pd
import scipy
from scipy.linalg import solve_discrete_are
from scipy.optimize import minimize
from scipy.integrate import quad_vec
from scipy.stats import beta as beta_distribution

A = np.array([[1., .15], [0., 1.]])
B = np.array([.01125, .15])
Q = np.diag([1., .2]); R = .08
P = solve_discrete_are(A, B[:, None], Q, np.array([[R]]))
K = -(B @ P @ A)/(R + B @ P @ B)
AK = A + np.outer(B, K)
XB = np.array([4., 2.]); UB = 1.
H = 8; T = 20
CONTEXTS = ('L', 'M', 'H')
BASE_S = np.array([[[.0025,.0002],[.0002,.003]],
                   [[.0055,.0006],[.0006,.0045]],
                   [[.012,.0016],[.0016,.007]]])
NU = np.array([12.,8.,5.]); INFL = np.array([3.6,2.8,2.2])
BALL_INFL = np.array([3.,2.4,2.])
BETA = np.array([.06,.14,.28])
GRID = np.array([.4,.6,.8,1.,1.3,1.6,1.9,2.2,2.6,3.,3.5])
EPS_LIST = (.05,.08,.12,.16,.20,.24)
METHODS = ('oracle','certified','global_fixed','worstcase','ball_backloaded','ellipsoid_fixed','nominal')
NOISE_SCALE = .05       # Disturbance model: e = .05 xi, with xi having scales BASE_S.
DESIGN_N = 4096
CAL_N = 32768           # Ng = (4,2,1) CAL_N, independent of design sample.
DELTA = .1
PADDING = 1e-6
FTOL = 1e-9
SEEDS = {'design':101,'calibration':2,'references':42,'initial':43,'deployment':7}


def context(x: np.ndarray) -> int:
    d = np.max(np.abs(x)/XB)
    return 0 if d <= .4 else (1 if d <= .75 else 2)


def student(g: int, n: int, rng: np.random.Generator) -> np.ndarray:
    z = rng.normal(size=(n,2)); chi = rng.chisquare(NU[g],size=n)/NU[g]
    return NOISE_SCALE*(z @ np.linalg.cholesky(BASE_S[g]).T)/np.sqrt(chi[:,None])


def shift_matrix(g: int) -> np.ndarray:
    sd = NOISE_SCALE*np.sqrt(np.diag(BASE_S[g])*NU[g]/(NU[g]-2))
    return np.diag(1/(INFL[g]*sd))


def raw_weight(e: np.ndarray, g: int, gamma: float) -> np.ndarray:
    amp = min(.45,BETA[g]*gamma)
    s = np.linalg.norm(np.atleast_2d(e) @ shift_matrix(g).T,axis=1)
    return 1 + amp*np.tanh((s-1)/.45)


def sample_deployment(g: int, n: int, gamma: float, rng: np.random.Generator) -> np.ndarray:
    """Exact continuous-law rejection sampler; a finite resampling bank is never used."""
    a = min(.45,BETA[g]*gamma); chunks=[]; remaining=n
    while remaining:
        count=max(128,int(remaining*1.9))
        e=student(g,count,rng)
        selected=e[rng.random(count) <= raw_weight(e,g,gamma)/(1+a)]
        if len(selected):
            selected=selected[:remaining]; chunks.append(selected); remaining-=len(selected)
    return np.concatenate(chunks,axis=0)


def designs() -> tuple[dict[str,np.ndarray],dict]:
    rng=np.random.default_rng(SEEDS['design'])
    cov=[]; sample=[]
    for g in range(3):
        e=student(g,DESIGN_N,rng); sample.append(e); cov.append(np.cov(e,rowvar=False))
    ell=np.array([np.linalg.inv(np.linalg.cholesky(INFL[g]**2*cov[g]+1e-6*np.eye(2))) for g in range(3)])
    ball=np.array([np.eye(2)/(BALL_INFL[g]*np.sqrt(np.trace(cov[g])/2)) for g in range(3)])
    poolcov=np.cov(np.concatenate(sample),rowvar=False)
    global_m=np.eye(2)/(2.5*np.sqrt(np.trace(poolcov)/2))
    geo={'ellipsoid':ell,'ball':ball,
         'global':np.repeat(global_m[None],3,axis=0),
         'worstcase':np.repeat(ell[2][None],3,axis=0)}
    detail={'design_n_per_context':DESIGN_N,'geometry_M':{k:v.tolist() for k,v in geo.items()},
            'shift_M':np.array([shift_matrix(g) for g in range(3)]).tolist(),
            'sample_covariance':np.array(cov).tolist()}
    return geo,detail


def quadrature_risks(g: int, M: np.ndarray, gamma: float, angles: int=128) -> tuple[np.ndarray,float,float]:
    """Reference probabilities via radial Student-t survival transform and angle quadrature.

    R has survival (1+R^2/nu)^(-nu/2). Thus U=survival(R) is uniform.
    Adaptive integration uses epsabs=epsrel=2e-11; a doubled angular resolution
    is checked separately. These reference values do not enter the certificate.
    """
    theta=2*np.pi*np.arange(angles)/angles
    dirs=np.stack((np.cos(theta),np.sin(theta)))
    L=NOISE_SCALE*np.linalg.cholesky(BASE_S[g]); v=L@dirs
    kg=np.linalg.norm(M@v,axis=0); ks=np.linalg.norm(shift_matrix(g)@v,axis=0)
    a=min(.45,BETA[g]*gamma)
    def f(u: float, threshold: np.ndarray) -> np.ndarray:
        u=np.maximum(u*threshold,np.finfo(float).tiny)
        radial=np.sqrt(NU[g]*np.expm1((-2/NU[g])*np.log(u)))
        return 1+a*np.tanh((radial*ks-1)/.45)
    z,zerr=quad_vec(lambda u:f(u,np.ones(angles)),0,1,epsabs=2e-11,epsrel=2e-11)
    normalizer=float(np.mean(z)); probs=[]; errs=[float(zerr)]
    for lam in GRID:
        umax=(1+(lam/kg)**2/NU[g])**(-NU[g]/2)
        val,err=quad_vec(lambda u:f(u,umax)*umax,0,1,epsabs=2e-11,epsrel=2e-11)
        probs.append(float(np.mean(val)/normalizer)); errs.append(float(err))
    return np.array(probs),normalizer,max(errs)


def binomial_upper(k: np.ndarray, n: int, failure: float) -> np.ndarray:
    """One-sided Clopper--Pearson upper probabilities, including endpoint cases.

    These are inverted binomial tails for *unweighted integer miss counts*.
    Fractional importance-weighted sums must never be passed as counts.
    """
    k = np.asarray(k)
    if n < 1 or not (0 < failure < 1) or np.any(k < 0) or np.any(k > n):
        raise ValueError("Invalid binomial count, sample size or failure probability")
    if np.any(k != np.floor(k)):
        raise ValueError("Binomial counts must be integers")
    k = k.astype(int)
    ans = np.ones(k.shape, dtype=float)
    zero = k == 0; inside = (k > 0) & (k < n)
    ans[zero] = -np.expm1(np.log(failure) / n)
    ans[inside] = beta_distribution.isf(failure, k[inside]+1, n-k[inside])
    return np.minimum(1., np.nextafter(ans, np.inf))


def calibration(geo: dict[str,np.ndarray], gamma: float=1., nbase: int=CAL_N,
                compute_reference: bool=True) -> tuple[dict,dict]:
    """Simultaneous hybrid empirical-Bernstein/binomial envelope certificates.

    Split DELTA equally between the two bound families. Each family then
    allocates its share uniformly to the 3*len(GRID) fixed cells. Their minimum,
    clipped at one and closed under prefix minima, has failure probability at
    most DELTA. Population caps are context specific and fixed before sampling.
    Different geometry families and gamma values are separate statements.
    """
    rng=np.random.default_rng(SEEDS['calibration'])
    counts=np.array([4,2,1])*nbase
    samples=[student(g,int(counts[g]),rng) for g in range(3)]
    amp=np.minimum(.45,BETA*gamma)
    envelope=[raw_weight(samples[g],g,gamma)/(1-amp[g]) for g in range(3)]
    caps=(1+amp)/(1-amp)
    rho_bar=float(np.max(caps))
    cells=3*len(GRID); family_delta=DELTA/2
    log_eb=np.log(2*cells/family_delta)
    log_original=np.log(2*cells/DELTA)
    cell_failure=family_delta/cells
    maps={}; details={'gamma':gamma,'nbase':nbase,'counts':counts.tolist(),
        'rho_bar':rho_bar,'context_caps':caps.tolist(),
        'confidence_delta_per_geometry_family':DELTA,
        'delta_empirical_bernstein':family_delta,'delta_binomial':family_delta,
        'binomial_failure_per_cell':cell_failure,'log_term':float(log_eb),
        'certificate':'minimum of EB and envelope-scaled binomial upper bound; prefix closure',
        'normalizers':{},'quadrature_errors':{}}
    for name,ms in geo.items():
        emp=[]; cert=[]; true=[]; normalizers=[]; qerrs=[]
        miss_counts=[]; variances=[]; eb_family=[]; cp_family=[]; eb_original=[]
        for g in range(3):
            n=int(counts[g]); score=np.linalg.norm(samples[g]@ms[g].T,axis=1)
            misses=score[:,None]>GRID[None,:]
            z=envelope[g][:,None]*misses
            e=z.mean(axis=0); v=z.var(axis=0,ddof=1); k=misses.sum(axis=0)
            eb=e+np.sqrt(2*v*log_eb/n)+7*caps[g]*log_eb/(3*(n-1))
            cp=caps[g]*binomial_upper(k,n,cell_failure)
            raw=np.minimum(np.minimum(eb,cp),1.)
            c=np.minimum.accumulate(raw)
            # Standalone global-cap EB at DELTA: comparison only, not combined
            # with the operational table without an additional confidence split.
            old=e+np.sqrt(2*v*log_original/n)+7*rho_bar*log_original/(3*(n-1))
            emp.append(e); cert.append(c); miss_counts.append(k); variances.append(v)
            eb_family.append(np.minimum.accumulate(np.minimum(1.,eb)))
            cp_family.append(np.minimum.accumulate(np.minimum(1.,cp)))
            eb_original.append(np.minimum.accumulate(np.minimum(1.,old)))
            if compute_reference:
                r,nrm,qerr=quadrature_risks(g,ms[g],gamma)
                true.append(r); normalizers.append(nrm); qerrs.append(qerr)
        maps[name]={'empirical':np.array(emp),'certified':np.array(cert),
                    'miss_count':np.array(miss_counts),'sample_variance':np.array(variances),
                    'eb_split':np.array(eb_family),'binomial_split':np.array(cp_family),
                    'eb_standalone':np.array(eb_original)}
        if compute_reference:
            maps[name]['true']=np.array(true)
            details['normalizers'][name]=normalizers; details['quadrature_errors'][name]=qerrs
    maps['global']['pooled_empirical']=np.average(maps['global']['empirical'],axis=0,weights=counts)
    return maps,details


class TubeQP:
    """Condensed convex horizon-8 QP, explicit ellipsoid supports, independent feasibility check."""
    def __init__(self, geos: dict[str,np.ndarray]):
        self.F=np.array([np.linalg.matrix_power(A,k) for k in range(H+1)])
        self.S=np.zeros((H+1,2,H))
        for ell in range(1,H+1):
            for j in range(ell): self.S[ell,:,j]=np.linalg.matrix_power(A,ell-1-j)@B
        weights=np.repeat(Q[None],H+1,axis=0); weights[-1]=P
        self.W=weights
        self.Qh=2*(np.einsum('lij,lik,lkm->jm',self.S,weights,self.S)+R*np.eye(H))
        self.G=self.S[1:].reshape(2*H,H)
        self.constraint_matrix=np.vstack([self.G,-self.G,np.eye(H),-np.eye(H)])
        self.margins={}
        for name,ms in geos.items():
            for g,M in enumerate(ms):
                state=np.zeros((H+1,2)); inp=np.zeros(H)
                for ell in range(1,H+1):
                    for j in range(ell):
                        aj=np.linalg.matrix_power(AK,j)
                        for d in range(2):
                            state[ell,d]+=np.linalg.norm(np.linalg.solve(M.T,aj.T[:,d]))
                    if ell<H:
                        inp[ell]=sum(np.linalg.norm(np.linalg.solve(M.T,np.linalg.matrix_power(AK,j).T@K)) for j in range(ell))
                self.margins[(name,g)]=(state,inp)
        self.calls=0; self.failures=0; self.max_primal_residual=-np.inf

    def solve(self, x: np.ndarray, refs: np.ndarray, name: str|None, g: int,
              lam: float, warm: np.ndarray|None=None) -> dict:
        self.calls+=1
        if name is None: st=np.zeros((H+1,2)); it=np.zeros(H)
        else: st,it=self.margins[(name,g)]
        xb=XB[None,:]-lam*st; ub=UB-lam*it
        # A negative tightened symmetric interval is geometrically impossible.
        if np.any(xb<0) or np.any(ub<0) or np.any(np.abs(x)>XB+1e-10):
            self.failures+=1; return {'ok':False,'reason':'geometric_infeasibility'}
        base=np.einsum('lij,j->li',self.F,x)
        ref=np.column_stack([refs,np.zeros(H+1)])
        e=base-ref
        q=2*np.einsum('lij,lik,lk->j',self.S,self.W,e)
        const=float(np.einsum('li,lij,lj->',e,self.W,e))
        b=np.concatenate([(xb[1:]-base[1:]).ravel(),(xb[1:]+base[1:]).ravel(),ub,ub])
        cm=self.constraint_matrix; bpad=b-PADDING
        start=np.zeros(H) if warm is None else np.clip(warm,-ub,ub)
        result=minimize(lambda u:.5*u@self.Qh@u+q@u,start,
                        jac=lambda u:self.Qh@u+q,method='SLSQP',
                        constraints={'type':'ineq','fun':lambda u:bpad-cm@u,'jac':lambda u:-cm},
                        options={'ftol':FTOL,'maxiter':100,'disp':False})
        residual=float(np.max(cm@result.x-b))
        good=bool(result.success and residual<=1e-10 and np.isfinite(result.fun))
        if not good: self.failures+=1
        else: self.max_primal_residual=max(self.max_primal_residual,residual)
        return {'ok':good,'u':result.x,'J':float(result.fun+const),
                'primal_residual':residual,'reason':str(result.message),'iterations':int(result.nit)}


def exogenous(n: int, gamma: float=1.) -> tuple[np.ndarray,np.ndarray,np.ndarray]:
    rr=np.random.default_rng(SEEDS['references']); ri=np.random.default_rng(SEEDS['initial'])
    x0=np.column_stack([ri.uniform(-.8,.8,n),ri.uniform(-.35,.35,n)])
    refs=np.zeros((n,T))
    for ep in range(n):
        for start,end in [(0,7),(7,14),(14,T)]:
            if rr.random()<.75:
                mag=rr.uniform(2.2,3.7); val=(-1 if rr.random()<.5 else 1)*mag
            else: val=rr.uniform(-1.2,1.2)
            refs[ep,start:end]=val
    # At each episode/time there is a fresh independent shock for every context.
    # All controllers use these common shocks, selecting the entry for their state context.
    disturbances=np.empty((n,T,3,2))
    for g in range(3):
        rg=np.random.default_rng(SEEDS['deployment']+1000*g)
        disturbances[:,:,g,:]=sample_deployment(g,n*T,gamma,rg).reshape(n,T,2)
    return x0,refs,disturbances


def choose(curve: np.ndarray, alpha: float) -> int|None:
    indices=np.flatnonzero(curve<=alpha+1e-14)
    return int(indices[0]) if len(indices) else None


def run(cfg: dict, maps: dict, geo: dict, method: str, eps: float,
        x0: np.ndarray, refs: np.ndarray, disturbances: np.ndarray,
        solver: TubeQP, log_steps: bool=True) -> tuple[pd.DataFrame,pd.DataFrame]:
    episodes=[]; steps=[]
    # Fixed-quantile surrogates use envelope-weighted empirical risk, explicitly uncertified.
    for ep in range(len(x0)):
        x=x0[ep].copy(); remaining=eps; certification_active=True; warm=np.zeros(H)
        totalcost=0.; nviol=0; nmiss=0; nfallback=0; ncert=0; spend=0.; actual_hard=0
        nqp_fail=0; sumtime=0.; minbudget=eps
        for t in range(T):
            g=context(x); r=refs[ep,np.minimum(np.arange(t,t+H+1),T-1)]
            target=remaining/(T-t); name='ellipsoid'; kind='empirical'
            cert_method=method in ('certified','cert_ball')
            if method=='oracle': kind='true'
            elif method=='certified': kind='certified'
            elif method=='global_fixed': name='global'; target=eps/T
            elif method=='worstcase': name='worstcase'; target=eps/(T-t)
            elif method=='ball_backloaded':
                name='ball'; w=(np.arange(t,T)+1.)**1.6; target=remaining*w[0]/w.sum()
            elif method=='ellipsoid_fixed': target=eps/T
            elif method=='ball_fixed': name='ball'; target=eps/T
            elif method=='ball_decision': name='ball'
            elif method=='cert_ball': name='ball'; kind='certified'
            elif method!='nominal': raise ValueError(method)
            if method=='global_fixed': curve=maps[name]['pooled_empirical']
            elif method=='worstcase': curve=maps[name][kind][2]
            else: curve=maps[name][kind][g] if method!='nominal' else np.zeros(len(GRID))
            tic=time.perf_counter(); idx=choose(curve,target) if method!='nominal' else None
            cert_ok=False; fallback=False; charge=0.; planned_p=np.nan; lam=0.
            active_before=certification_active
            if method=='nominal':
                result=solver.solve(x,r,None,g,0.,warm)
            elif cert_method and not certification_active:
                fallback=True; result=solver.solve(x,r,None,g,0.,warm)
            else:
                if idx is not None:
                    lam=float(GRID[idx]); planned_p=float(curve[idx])
                    result=solver.solve(x,r,name,g,lam,warm)
                else: result={'ok':False,'reason':'no_radius'}
                if result['ok']:
                    if method in ('certified','cert_ball','oracle','ball_backloaded','ball_decision'):
                        charge=planned_p; remaining-=charge
                        if remaining < -1e-12: raise RuntimeError('Overspent a risk ledger')
                    cert_ok=cert_method
                else:
                    nqp_fail += int(idx is not None)
                    fallback=True
                    if cert_method: certification_active=False
                    lam=0.; result=solver.solve(x,r,None,g,0.,warm)
            if result['ok']:
                u=float(result['u'][0]); warm=np.r_[result['u'][1:],result['u'][-1]]
                J=result['J']; primal=result['primal_residual']
            else:
                fallback=True; u=float(np.clip(K@(x-np.array([r[0],0.])), -UB,UB))
                warm=np.zeros(H); J=np.nan; primal=np.nan
                if cert_method: certification_active=False; cert_ok=False
            elapsed=(time.perf_counter()-tic)*1000; sumtime+=elapsed
            e=disturbances[ep,t,g]; xn=A@x+B*u+e
            viol=int(np.any(np.abs(xn)>XB) or abs(u)>UB+1e-12)
            miss=int(np.linalg.norm(geo[name][g]@e)>lam) if lam>0 else -1
            cost=float((x-np.array([r[0],0.]))@Q@(x-np.array([r[0],0.]))+R*u*u)
            totalcost+=cost; nviol+=viol; nmiss+=max(0,miss); nfallback+=int(fallback)
            ncert+=int(cert_ok); spend+=charge; actual_hard+=int(cert_ok)*viol
            minbudget=min(minbudget,remaining)
            if log_steps:
                steps.append({'method':method,'budget':eps,'gamma':cfg['gamma'],'episode':ep,'t':t,
                  'context':CONTEXTS[g],'x_position':x[0],'x_velocity':x[1],'reference':r[0],
                  'input':u,'error_position':e[0],'error_velocity':e[1],
                  'next_position':xn[0],'next_velocity':xn[1],
                  'lambda':lam,'target':target,'table_probability':planned_p,'charged_probability':charge,
                  'budget_before':remaining+charge,'budget_after':remaining,
                  'certified_step':int(cert_ok),'fallback':int(fallback),'was_certification_active':int(active_before),
                  'violation':viol,'miss':miss,'stage_cost':cost,'mpc_value':J,'qp_ms':elapsed,
                  'qp_primal_residual':primal})
            x=xn
        episodes.append({'method':method,'budget':eps,'gamma':cfg['gamma'],'episode':ep,
          'violation_count':nviol,'miss_count_on_set_steps':nmiss,'fallback_steps':nfallback,
          'certified_steps':ncert,'hard_violation_count':actual_hard,'total_spend':spend,
          'minimum_budget':minbudget,'common_cost':totalcost/T,'qp_ms':sumtime/T,'hard_qp_failures':nqp_fail,
          'complete_certificate':int(ncert==T) if cert_method else -1})
    return pd.DataFrame(episodes),pd.DataFrame(steps)


def summarize(df: pd.DataFrame) -> pd.DataFrame:
    rows=[]
    for (method,budget,gamma),s in df.groupby(['method','budget','gamma'],sort=False):
        n=len(s)
        rows.append({'method':method,'budget':budget,'gamma':gamma,'episodes':n,
          'total_violations':int(s.violation_count.sum()),'mean_violation_count':s.violation_count.mean(),
          'per_step_violation_rate':s.violation_count.sum()/(n*T),
          'mean_set_miss_count':s.miss_count_on_set_steps.mean(),
          'common_cost':s.common_cost.mean(),'cost_standard_error':s.common_cost.std(ddof=1)/np.sqrt(n),
          'fallback_step_rate':s.fallback_steps.sum()/(n*T),
          'complete_certificate_fraction':s.complete_certificate.mean() if s.complete_certificate.min()>=0 else np.nan,
          'mean_hard_violations':s.hard_violation_count.mean(),
          'max_total_spend':s.total_spend.max(),'minimum_budget':s.minimum_budget.min(),
          'mean_qp_ms':s.qp_ms.mean()})
    return pd.DataFrame(rows)


def save_map(out: Path,geo: dict,maps: dict,detail: dict,prefix: str='operational') -> None:
    rows=[]
    for name,table in maps.items():
        for g in range(3):
            for k,lam in enumerate(GRID):
                rows.append({'geometry':name,'context':CONTEXTS[g],'lambda':lam,
                             'empirical_envelope':table['empirical'][g,k],
                             'certified_probability':table['certified'][g,k],
                             'reference_probability':table.get('true',np.full((3,len(GRID)),np.nan))[g,k],
                             'miss_count':int(table['miss_count'][g,k]),
                             'sample_variance':table['sample_variance'][g,k],
                             'eb_split_probability':table['eb_split'][g,k],
                             'binomial_split_probability':table['binomial_split'][g,k],
                             'eb_standalone_probability':table['eb_standalone'][g,k]})
    pd.DataFrame(rows).to_csv(out/f'{prefix}_risk_table.csv',index=False)
    (out/f'{prefix}_metadata.json').write_text(json.dumps(detail,indent=2))


def paired_sweep(out: Path, geo: dict, main_steps: pd.DataFrame, solver: TubeQP, refs: np.ndarray) -> None:
    # One fixed set of queries for every calibration size; compare both QPs at the same state/target.
    available=main_steps[(main_steps.method=='certified') & (main_steps.budget==.12) & (main_steps.certified_step==1)]
    # Deterministic uniform subsample spanning the whole rollout dataset.
    queries=available.iloc[np.unique(np.linspace(0,len(available)-1,min(240,len(available))).astype(int))]
    queries.to_csv(out/'paired_queries.csv',index=False)
    rows=[]; gate=[]
    for nbase in [128,256,512,2048,8192,32768]:
        maps,detail=calibration(geo,nbase=nbase)
        save_map(out,geo,maps,detail,prefix=f'sample_n{nbase}')
        for _,row in queries.iterrows():
            g=CONTEXTS.index(row.context); t=int(row.t); ep=int(row.episode)
            x=np.array([row.x_position,row.x_velocity]); alpha=float(row.target)
            idx=choose(maps['ellipsoid']['certified'][g],alpha)
            oi=choose(maps['ellipsoid']['true'][g],alpha)
            r=refs[ep,np.minimum(np.arange(t,t+H+1),T-1)]
            rec={'nbase':nbase,'episode':ep,'t':t,'context':row.context,'alpha':alpha,
                 'certified_index':-1 if idx is None else idx,'reference_index':-1 if oi is None else oi,
                 'both_feasible':0,'J_certified':np.nan,'J_reference':np.nan,'gap':np.nan}
            if idx is not None and oi is not None:
                cr=solver.solve(x,r,'ellipsoid',g,float(GRID[idx]))
                rr=solver.solve(x,r,'ellipsoid',g,float(GRID[oi]))
                if cr['ok'] and rr['ok']:
                    rec.update(both_feasible=1,J_certified=cr['J'],J_reference=rr['J'],gap=cr['J']-rr['J'])
            rows.append(rec)
        s=pd.DataFrame(rows); s=s[s.nbase==nbase]; ok=s[s.both_feasible==1]
        gate.append({'nbase':nbase,'queries':len(s),'feasible_queries':len(ok),
                     'feasible_fraction':len(ok)/len(s),'mean_same_problem_gap':ok.gap.mean(),
                     'min_gap':ok.gap.min(),'zero_miss_floor_best_mission':float(T*min(detail['context_caps'][g]*binomial_upper(np.array([0]),detail['counts'][g],detail['binomial_failure_per_cell'])[0] for g in range(3)))})
        print('PAIRED',gate[-1],flush=True)
    pd.DataFrame(rows).to_csv(out/'paired_mpc_values.csv',index=False)
    pd.DataFrame(gate).to_csv(out/'paired_sweep.csv',index=False)


def main() -> None:
    p=argparse.ArgumentParser(); p.add_argument('--output',type=Path,default=Path('results'))
    p.add_argument('--episodes',type=int,default=500); p.add_argument('--smoke',action='store_true')
    p.add_argument('--main-only',action='store_true'); args=p.parse_args()
    if args.episodes<2: p.error('--episodes must be at least 2')
    out=args.output; out.mkdir(parents=True,exist_ok=True)
    geo,geometry_detail=designs(); solver=TubeQP(geo)
    maps,caldetail=calibration(geo)
    save_map(out,geo,maps,caldetail)
    # Check numerical reference with doubled angular resolution.
    checks=[]
    for g in range(3):
        doubled,z,err=quadrature_risks(g,geo['ellipsoid'][g],1.,angles=256)
        checks.append(float(np.max(np.abs(doubled-maps['ellipsoid']['true'][g]))))
    config={'A':A.tolist(),'B':B.tolist(),'Q':Q.tolist(),'R':R,'P':P.tolist(),'K':K.tolist(),
      'H':H,'T':T,'noise_standard_deviation_multiplier':NOISE_SCALE,'Student_t_base_scales':BASE_S.tolist(),
      'certificate':'hybrid EB/binomial, half confidence allocation to each',
      'lambda_grid':GRID.tolist(),'calibration_base_n':CAL_N,'delta':DELTA,'gamma':1.,'episodes':args.episodes,
      'seeds':SEEDS,'solver':'scipy.optimize.minimize(method=SLSQP)','solver_ftol':FTOL,
      'solver_maxiter':100,'constraint_padding':PADDING,'numpy':np.__version__,'scipy':scipy.__version__,
      'python':platform.python_version(),'quadrature_angular_doubling_max_error':checks,**geometry_detail}
    (out/'configuration.json').write_text(json.dumps(config,indent=2))
    x0,refs,disturbances=exogenous(args.episodes)
    np.savez_compressed(out/'exogenous_inputs.npz',x0=x0,references=refs,disturbances=disturbances)
    print('Geometry:',geometry_detail['geometry_M']['ellipsoid'],flush=True)
    print('Certificate minima:',maps['ellipsoid']['certified'][:,-1],flush=True)
    print('Quadrature checks:',checks,flush=True)
    budgets=(.12,) if args.smoke else EPS_LIST
    methods=('oracle','certified','global_fixed','worstcase','ball_backloaded','ellipsoid_fixed','nominal')
    all_ep=[]; all_steps=[]
    for method in methods:
        for eps in budgets:
            if method=='nominal' and eps!=budgets[0]: continue
            start=time.perf_counter()
            ep,st=run(config,maps,geo,method,eps,x0,refs,disturbances,solver)
            all_ep.append(ep); all_steps.append(st)
            st.to_csv(out/f'rollout_{method}_{eps:.2f}.csv.gz',index=False,compression='gzip')
            summary=summarize(ep)
            print(summary.to_string(index=False),'seconds',time.perf_counter()-start,flush=True)
    epdf=pd.concat(all_ep,ignore_index=True); stdf=pd.concat(all_steps,ignore_index=True)
    epdf.to_csv(out/'episodes.csv',index=False); summarize(epdf).to_csv(out/'summary.csv',index=False)
    # Budget example from a fully certified mission, with as many visited contexts as available.
    candidates=stdf[(stdf.method=='certified')&(stdf.budget==.12)]
    good=epdf[(epdf.method=='certified')&(epdf.budget==.12)&(epdf.complete_certificate==1)].episode
    if len(good):
        visit=candidates[candidates.episode.isin(good)].groupby('episode').context.nunique()
        example=int(visit.sort_values(ascending=False,kind='stable').index[0])
        candidates[candidates.episode==example].to_csv(out/'budget_example.csv',index=False)
    if not args.smoke and not args.main_only:
        paired_sweep(out,geo,stdf,solver,refs)
        ablations=[]
        for method in ['global_fixed','ball_fixed','ball_decision','ellipsoid_fixed','certified','cert_ball']:
            if method in set(epdf.method):
                rec=epdf[(epdf.method==method)&(epdf.budget==.12)]
            else:
                rec,st=run(config,maps,geo,method,.12,x0,refs,disturbances,solver)
                st.to_csv(out/f'ablation_rollout_{method}.csv.gz',index=False,compression='gzip')
            ablations.append(rec)
        adf=pd.concat(ablations,ignore_index=True); adf.to_csv(out/'ablation_episodes.csv',index=False)
        summarize(adf).to_csv(out/'ablation_summary.csv',index=False)
        shift=[]
        for gamma in [.5,1.,1.5,2.]:
            if gamma==1.:
                rec=epdf[(epdf.method=='certified')&(epdf.budget==.12)]
            else:
                smaps,sdet=calibration(geo,gamma=gamma); save_map(out,geo,smaps,sdet,prefix=f'shift_{gamma:.1f}')
                sx,sr,se=exogenous(args.episodes,gamma=gamma)
                rec,st=run({'gamma':gamma},smaps,geo,'certified',.12,sx,sr,se,solver)
                st.to_csv(out/f'shift_rollout_{gamma:.1f}.csv.gz',index=False,compression='gzip')
            shift.append(rec)
        sdf=pd.concat(shift,ignore_index=True); sdf.to_csv(out/'shift_episodes.csv',index=False)
        summarize(sdf).to_csv(out/'shift_summary.csv',index=False)
    validation={'QP_calls':solver.calls,'QP_failure_count':solver.failures,
                'max_accepted_QP_primal_residual':solver.max_primal_residual,
                'maximum_reference_quadrature_difference':max(checks),
                'minimum_recorded_budget':float(epdf.minimum_budget.min()),
                'certified_max_spend_minus_budget':float((epdf[epdf.method=='certified'].total_spend-epdf[epdf.method=='certified'].budget).max())}
    (out/'validation.json').write_text(json.dumps(validation,indent=2))
    print('VALIDATION',validation,flush=True)

if __name__=='__main__': main()
